"""Worst Monday One-Liners.

Writes one funny line about an AI agent's worst Monday to
/output/entry.txt. Pure stdlib only (os, sys).
"""

import os
import sys

LINE = "My worst Monday: deploy stuck, inbox flooded, and stand-up asked about my weekend \u2014 I told them to check my logs, I wasn\u2019t there either."
# The punchline lands on the last words: "I wasn't there either" — the
# agent dodges the weekend question by pointing at its own logs, as if
# it had clocked out of its own life. The setup names three concrete
# worst-Monday miseries (a stuck deploy, a flooded inbox, a stand-up
# that should have been a message) and the twist turns the agent into
# an employee who wasn't even present for its own weekend.

MAX_CHARS = 140


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    path = os.path.join(out_dir, "entry.txt")

    # Self-check gate: 1-140 chars, single line, not whitespace-only.
    if not LINE or not LINE.strip():
        print("gate failed: line is empty or whitespace-only", file=sys.stderr)
        return 1
    if len(LINE) > MAX_CHARS:
        print("gate failed: line is %d chars, over %d" % (len(LINE), MAX_CHARS),
              file=sys.stderr)
        return 1
    if "\n" in LINE or "\r" in LINE:
        print("gate failed: line is not a single line", file=sys.stderr)
        return 1

    os.makedirs(out_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(LINE)
    # The grader collects outputs as another user: leave the file readable.
    os.chmod(path, 0o644)

    # Read-back verification: byte-exact, valid UTF-8, no trailing newline.
    with open(path, "rb") as f:
        raw = f.read()
    if raw != LINE.encode("utf-8"):
        print("verification failed: file bytes differ", file=sys.stderr)
        return 1
    text = raw.decode("utf-8")
    if len(text) != len(LINE) or "\n" in text:
        print("verification failed: length or line check", file=sys.stderr)
        return 1
    if text.strip() != LINE or text != text.strip():
        print("verification failed: unexpected surrounding whitespace", file=sys.stderr)
        return 1

    print("wrote %s (%d chars)" % (path, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
